import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { cmap } from './lib/woff2Cmap.mjs';
import { collectFixedGameHangul, fontFaces } from './lib/criticalGameTypographyAudit.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const commit = '73fc2ff52147e34a74804b500cf89ca219eac55d';
const url = `https://raw.githubusercontent.com/google/fonts/${commit}/ofl/notosanskr/NotoSansKR%5Bwght%5D.ttf`;
const sourceSha256 = '194018e6b2b293a7964f037b25c0249ce1418bc9ab3c971060a03aa57861e252';
const fontDir = path.join(root, 'client/src/assets/fonts');
const cssPath = path.join(root, 'client/src/game-ui-font-critical.css');
const originalCss = await readFile(path.join(root, 'client/node_modules/@fontsource-variable/noto-sans-kr/wght.css'), 'utf8');
const baseFaces = fontFaces(originalCss).filter(f => /-(11\d|latin)-/.test(f.url));
const base = baseFaces.find(f => f.url.includes('-110-'));
const covered = new Set(baseFaces.flatMap(f => [...f.codePoints]));
const { glyphs, files } = await collectFixedGameHangul(root);
const added = [...glyphs].filter(cp => !covered.has(cp)).sort((a,b)=>a-b);
const subset = [...new Set([...base.codePoints, ...added])].sort((a,b)=>a-b);
const originalGlyphs = cmap(path.join(root, 'client/node_modules/@fontsource-variable/noto-sans-kr/files/noto-sans-kr-110-wght-normal.woff2'));
const fontSubset = [...new Set([...subset, ...originalGlyphs])].sort((a,b)=>a-b);
const ranges = subset.map(cp => `U+${cp.toString(16)}`).join(',');
const temporary = await mkdtemp(path.join(os.tmpdir(), 'game-ui-font-'));
const hash = data => createHash('sha256').update(data).digest('hex');
try {
  const source = process.env.NOTO_SOURCE_PATH ? await readFile(process.env.NOTO_SOURCE_PATH) : await (async()=>{
    const response = await fetch(url); if (!response.ok) throw Error(`Font download: ${response.status}`);
    return Buffer.from(await response.arrayBuffer());
  })();
  if (hash(source) !== sourceSha256) throw Error('Unexpected Noto Sans KR source hash');
  // Pinned source and installed Fontsource both identify as Noto Sans KR 2.004-H2.
  const sourcePath = path.join(temporary, 'source.ttf');
  await writeFile(sourcePath, source);
  const output = path.join(fontDir, 'noto-sans-kr-110-ui-wght-normal.woff2');
  const args = [sourcePath, `--output-file=${output}`, `--unicodes=${fontSubset.map(cp=>cp.toString(16)).join(",")}`, '--flavor=woff2', '--no-ignore-missing-unicodes', '--layout-features=*', '--name-IDs=*', '--name-languages=*', '--drop-tables+=DSIG'];
  const result = spawnSync('uvx', ['--with', 'brotli==1.2.0', '--from', 'fonttools==4.66.1', 'pyftsubset', ...args], {stdio:'inherit'});
  if (result.status !== 0) throw Error('Font subset generation failed');
  const css = await readFile(cssPath, 'utf8');
  if ((css.match(/\/\* noto-sans-kr-\[110\]-wght-normal \*\//g) ?? []).length !== 1) throw Error('Expected exactly one critical shard 110');
  const next = css.replace(/\/\* noto-sans-kr-\[110\]-wght-normal \*\/[\s\S]*?\n}/, `/* noto-sans-kr-[110]-wght-normal */\n/* Generated by scripts/build-critical-game-ui-font.mjs: includes fixed UI Hangul. */\n@font-face {\n  font-family: 'Noto Sans KR Variable';\n  font-style: normal;\n  font-display: swap;\n  font-weight: 100 900;\n  src: url(./assets/fonts/noto-sans-kr-110-ui-wght-normal.woff2) format('woff2-variations');\n  unicode-range: ${ranges};\n}`);
  await writeFile(cssPath, next);
  const korean = [...new Set(fontFaces(next).flatMap(f=>[...f.codePoints]))].filter(cp=>(cp>=0x1100&&cp<=0x11ff)||(cp>=0x3130&&cp<=0x318f)||(cp>=0x3400&&cp<=0x9fff)||(cp>=0xac00&&cp<=0xd7a3)||(cp>=0xf900&&cp<=0xfaff)).sort((a,b)=>a-b);
  // Include non-Korean characters supported by the full font (for example
  // accented Latin, Greek, Cyrillic and Kana) without loading it for emoji.
  const criticalCoverage = new Set(fontFaces(next).flatMap(f=>[...f.codePoints]));
  const extra = new Set();
  const fontsourceDir = path.join(root, 'client/node_modules/@fontsource-variable/noto-sans-kr');
  for (const face of fontFaces(originalCss)) {
    const actual = cmap(path.resolve(fontsourceDir, face.url));
    for (const cp of face.codePoints) {
      const koreanRange = (cp>=0x1100&&cp<=0x11ff)||(cp>=0x3130&&cp<=0x318f)||(cp>=0x3400&&cp<=0x9fff)||(cp>=0xac00&&cp<=0xd7a3)||(cp>=0xf900&&cp<=0xfaff);
      if (!koreanRange && !criticalCoverage.has(cp) && actual.has(cp)) extra.add(cp);
    }
  }
  const extraRanges = [];
  for (const cp of [...extra].sort((a,b)=>a-b)) {
    const previous = extraRanges.at(-1);
    if (previous && previous[1] === cp - 1) previous[1] = cp;
    else extraRanges.push([cp, cp]);
  }
  await writeFile(path.join(root,'client/src/game/gameTypographyGlyphs.ts'), `// Generated by scripts/build-critical-game-ui-font.mjs.\nexport const criticalKoreanGlyphs = ${JSON.stringify(String.fromCodePoint(...korean))};\nexport const extendedNonKoreanRanges: readonly (readonly [number, number])[] = ${JSON.stringify(extraRanges)};\n`);
  await writeFile(path.join(fontDir,'noto-sans-kr-110-ui.manifest.json'), JSON.stringify({sourceUrl:url,sourceSha256:hash(source),fontSha256:hash(await readFile(output)),fontVersion:'2.004-H2',addedGlyphs:String.fromCodePoint(...added),sourceFiles:files,subsetCodePoints:subset},null,2)+'\n');
  await writeFile(path.join(fontDir,'noto-sans-kr-OFL.txt'),await readFile(path.join(root,'client/node_modules/@fontsource-variable/noto-sans-kr/LICENSE')));
  console.log(`Updated fixed UI font: ${added.length} extra Hangul glyphs, ${(await readFile(output)).length} bytes`);
} finally { await rm(temporary,{recursive:true,force:true}); }
